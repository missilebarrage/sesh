describe("Format", function()
	local function Load()
		local _, ns = Harness.Load()
		return ns.Format
	end

	it("groups thousands, including amounts beyond 32-bit integers", function()
		local Format = Load()
		expect(Format.Integer(0)).toBe("0")
		expect(Format.Integer(999)).toBe("999")
		expect(Format.Integer(1000)).toBe("1,000")
		expect(Format.Integer(152340)).toBe("152,340")
		expect(Format.Integer(-1234567)).toBe("-1,234,567")
		expect(Format.Integer(98765432101)).toBe("98,765,432,101")
	end)

	it("abbreviates large numbers", function()
		local Format = Load()
		expect(Format.Compact(950)).toBe("950")
		expect(Format.Compact(9999)).toBe("9,999")
		expect(Format.Compact(68240)).toBe("68.2k")
		expect(Format.Compact(452000)).toBe("452k")
		expect(Format.Compact(1240000)).toBe("1.24M")
	end)

	it("writes plain money for chat and drops zero denominations", function()
		local Format = Load()
		expect(Format.MoneyText(103305)).toBe("10g 33s 5c")
		expect(Format.MoneyText(100000)).toBe("10g")
		expect(Format.MoneyText(5)).toBe("5c")
		expect(Format.MoneyText(0)).toBe("0c")
		expect(Format.MoneyText(30000000005)).toBe("3,000,000g 5c")
	end)

	it("writes compact plain-text money and hourly rates for detail lines", function()
		local Format = Load()
		expect(Format.MoneyShortText(12345678)).toBe("1,234g")
		expect(Format.MoneyShortText(123000)).toBe("12g 30s")
		expect(Format.MoneyShortText(1854)).toBe("18s 54c")
		expect(Format.MoneyShortText(7)).toBe("7c")
		expect(Format.PerHour(1854, Format.MoneyShortText)).toBe("18s 54c / hour")
		expect(Format.PerHour(nil, Format.MoneyShortText)).toBeNil()
	end)

	it("rounds money down to its largest denomination", function()
		local Format = Load()
		expect(Format.MoneyRough(31234)).toBe("3g")
		expect(Format.MoneyRough(4567)).toBe("45s")
		expect(Format.MoneyRough(12)).toBe("12c")
	end)

	it("adds coin icons for the UI", function()
		local Format = Load()
		expect(Format.Money(103305)).toBe(
			"10|TInterface\\MoneyFrame\\UI-GoldIcon:0:0:2:0|t 33|TInterface\\MoneyFrame\\UI-SilverIcon:0:0:2:0|t "
				.. "5|TInterface\\MoneyFrame\\UI-CopperIcon:0:0:2:0|t"
		)
		expect(Format.MoneyShort(12345678)).toBe("1,234|TInterface\\MoneyFrame\\UI-GoldIcon:0:0:2:0|t")
		expect(Format.MoneyShort(123000)).toBe(
			"12|TInterface\\MoneyFrame\\UI-GoldIcon:0:0:2:0|t 30|TInterface\\MoneyFrame\\UI-SilverIcon:0:0:2:0|t"
		)
	end)

	it("formats durations", function()
		local Format = Load()
		expect(Format.Duration(45)).toBe("45s")
		expect(Format.Duration(754)).toBe("12m")
		expect(Format.Duration(8040)).toBe("2h 14m")
		expect(Format.Duration(277200)).toBe("3d 5h")
		expect(Format.Duration(-5)).toBe("0s")
	end)

	it("shows a loss with a minus sign", function()
		local Format = Load()
		expect(Format.MoneyText(-123456)).toBe("-12g 34s 56c")
		expect(Format.MoneyShortText(-123456)).toBe("-12g 34s")
		expect(Format.MoneyRough(-123456)).toBe("-12g")
		expect(Format.Money(-50)).toContain("-50")
		expect(Format.MoneyShort(-1234567)).toMatch("^%-123|T")
		expect(Format.MoneyText(-0.4)).toBe("0c")
	end)

	it("formats dates and 12-hour times", function()
		local Format = Load()
		local timestamp = os.time({ year = 2026, month = 10, day = 6, hour = 14, min = 4 })
		expect(Format.Date(timestamp)).toBe("Oct 6")
		expect(Format.Time(timestamp)).toBe("2:04 PM")
		expect(Format.DateLong(timestamp)).toBe("Tue, Oct 6, 2026")
		local midnight = os.time({ year = 2026, month = 10, day = 6, hour = 0, min = 5 })
		expect(Format.Time(midnight)).toBe("12:05 AM")
	end)
end)
